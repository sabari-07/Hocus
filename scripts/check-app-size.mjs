// App size budget (F-D6): an app's *behaviour* (src/app.ts, the defineApp contract: selectables, reducers,
// vocabulary) must stay small, proving the skeleton is lean. Screen design (main.tsx panels, 3D scene, models)
// is contract item 4 and is reported separately, not hidden. Writes docs/app-size.md.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const APPS = [
  { dir: 'apps/room-designer', budget: 300 },
  { dir: 'apps/planet-explorer', budget: 300 },
  { dir: 'examples/kitchen-board', budget: 150 },
];
const loc = (f) =>
  readFileSync(f, 'utf8')
    .split('\n')
    .filter((l) => l.trim() && !/^\s*(\/\/|\*|\/\*)/.test(l)).length;
const all = (d) => {
  const out = [];
  if (!existsSync(d)) return out;
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) out.push(...all(p));
    else if (/\.(ts|tsx)$/.test(f)) out.push(p);
  }
  return out;
};
const pkgLoc = (d) => all(d).reduce((a, f) => a + loc(f), 0);

let fail = 0;
const rows = [];
for (const a of APPS) {
  const behaviour = ['src/app.ts'].map((f) => join(a.dir, f)).filter(existsSync).reduce((s, f) => s + loc(f), 0);
  const visuals = all(join(a.dir, 'src')).filter((f) => !/app\.ts$/.test(f)).reduce((s, f) => s + loc(f), 0);
  const ok = behaviour <= a.budget;
  if (!ok) fail++;
  rows.push(`| ${a.dir} | ${behaviour} | ${a.budget} | ${visuals} | ${ok ? 'within budget' : '**over budget**'} |`);
  console.log(`${ok ? '✓' : '✗'} ${a.dir}: ${behaviour} lines of behaviour (budget ${a.budget}), ${visuals} lines of screen design`);
}
const core = ['core', 'input', 'vision', 'speech', 'three', 'ui', 'devtools'].map((p) => `| @hocus/${p} | ${pkgLoc(`packages/${p}/src`)} |`);
writeFileSync(
  'docs/app-size.md',
  `# App size budget\n\nGenerated by \`npm run app-size\`. Counts non-blank, non-comment lines.\n\n` +
    `"Behaviour" is \`src/app.ts\`: the \`defineApp\` contract (selectables, actions with pure reducers, vocabulary in three languages).\n` +
    `"Screen design" is everything else in the app's \`src/\`: \`main.tsx\` (mount, side panels, Judge Mode script), the three.js scene and procedural models.\n` +
    `Tracking, speech, parsing, fusion, dialogue, undo, replay, X-ray, Spellbook, settings and accessibility all come from the skeleton.\n\n` +
    `| App | Behaviour lines (app.ts) | Budget | Screen-design lines | Status |\n|---|---|---|---|---|\n${rows.join('\n')}\n\n` +
    `## Skeleton packages\n\n| Package | Lines |\n|---|---|\n${core.join('\n')}\n`,
);
process.exit(fail ? 1 : 0);
