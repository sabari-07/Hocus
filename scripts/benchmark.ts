/**
 * Benchmark: Hocus fusion vs simple baselines on SIMULATED users (seeded, reproducible).
 * Writes docs/benchmark.md. Every number in the write-up must come from this script.
 *   npm run bench            (default 600 trials per condition)
 *   BENCH_TRIALS=3000 npm run bench
 */
import { writeFileSync } from 'node:fs';
import { createEngine, replay, type HocusEvent, type PointerSample } from '@hocus/core';
import { makeTestApp, simulateUser, type SimObject, type SimUserOptions } from '@hocus/testkit';

const TRIALS = Number(process.env.BENCH_TRIALS ?? 600);
const SEED = Number(process.env.BENCH_SEED ?? 2026);

const objects: SimObject[] = Array.from({ length: 6 }, (_, i) => ({
  id: `obj-${i + 1}`,
  label: `Object ${i + 1}`,
  kind: 'block',
  caps: ['scalable', 'colorable'],
  rect: { x: 160 + (i % 3) * 360, y: 140 + Math.floor(i / 3) * 300, w: 90, h: 90 },
}));

const CONDITIONS: Array<{ name: string; o: Partial<SimUserOptions> }> = [
  { name: 'Steady mouse, typical lag', o: { jitter: 1, conf: 1, lagRange: [250, 450], earlyLeave: 0.1 } },
  { name: 'Hand tracking, typical lag', o: { jitter: 4, conf: 0.8, lagRange: [250, 500], earlyLeave: 0.25 } },
  { name: 'Hand tracking, slow network', o: { jitter: 5, conf: 0.75, lagRange: [450, 900], earlyLeave: 0.3 } },
  { name: 'Shaky hand, user moves on early', o: { jitter: 8, conf: 0.65, lagRange: [250, 600], earlyLeave: 0.6 } },
];

type Outcome = 'correct' | 'wrong' | 'ask' | 'none';
const topAt = (samples: PointerSample[], t: number) => {
  let best: PointerSample | null = null;
  for (const s of samples) if (!best || Math.abs(s.t - t) < Math.abs(best.t - t)) best = s;
  return best?.hits.slice().sort((a, b) => b.quality - a.quality)[0]?.id;
};

const app = makeTestApp(objects);
const engine = createEngine(app);
const results: Array<{ cond: string; rows: Record<string, Record<Outcome, number>> }> = [];

for (const c of CONDITIONS) {
  const tally: Record<string, Record<Outcome, number>> = {};
  const add = (k: string, o: Outcome) => ((tally[k] ??= { correct: 0, wrong: 0, ask: 0, none: 0 })[o] += 1);
  for (let i = 0; i < TRIALS; i++) {
    const opts: SimUserOptions = { seed: SEED, objects, jitter: 3, conf: 0.9, lagRange: [250, 500], earlyLeave: 0.2, dwellRange: [350, 900], hz: 30, ...c.o };
    const trial = simulateUser(opts, i, 10_000);
    // Hocus: the full engine with default parameters.
    const { state } = replay(engine, trial.events as HocusEvent[]);
    const d = state.decisions.at(-1);
    const r = d?.resolution;
    const score = (name: string, res: typeof r) => {
      if (res?.status === 'resolved') add(name, res.bindings.target?.kind === 'object' && res.bindings.target.id === trial.target ? 'correct' : 'wrong');
      else if (res?.status === 'ask') add(name, 'ask');
      else add(name, 'none');
    };
    score('Hocus (default 350 ms lag)', r);
    // Same engine after onboarding calibration measured this user's typical lag (midpoint of the range).
    const lag = ((opts.lagRange[0] + opts.lagRange[1]) / 2) | 0;
    const cal = replay(engine, trial.events as HocusEvent[], engine.initial({ config: { lagMs: lag } })).state.decisions.at(-1)?.resolution;
    score(`Hocus (calibrated, ${lag} ms lag)`, cal);
    // Baselines: a single sample at one moment, no evidence, never asks.
    const b = (name: string, t: number) => {
      const id = topAt(trial.samples, t);
      add(name, !id ? 'none' : id === trial.target ? 'correct' : 'wrong');
    };
    b('Pointer at final transcript', trial.finalT);
    b('Pointer at first interim (no lag model)', trial.seenT);
    b('Oracle: pointer at true word time', trial.tWordTrue);
  }
  results.push({ cond: c.name, rows: tally });
}

const pct = (n: number) => `${((n / TRIALS) * 100).toFixed(1)}%`;
let md = `# Benchmark: resolving "that" on simulated users\n\n`;
md += `Generated by \`npm run bench\` (\`scripts/benchmark.ts\`). Seed **${SEED}**, **${TRIALS}** trials per condition, 6 targets.\n\n`;
md += `**These are simulated users, not people.** The simulator (\`packages/testkit/src/simulate.ts\`) moves a pointer from a decoy object to a target, dwells, speaks "make that bigger" with a random recognizer lag, and sometimes leaves early. After speaking it keeps pointing (40%), drifts to empty space (30%) or moves to another object (30%). It is useful for comparing strategies, not for claiming real-world accuracy. Real recorded sessions go in \`tests/replays/\`.\n\n`;
md += `- **Correct**: bound to the intended object. **Wrong**: bound to another object (the costly error). **Ask**: Hocus asked which one. **None**: no target.\n`;
md += `- Baselines take one pointer sample at one moment and never ask. The oracle knows the true word time, which no real system does.\n\n`;
for (const r of results) {
  md += `## ${r.cond}\n\n| Strategy | Correct | Wrong | Ask | None |\n|---|---|---|---|---|\n`;
  for (const [k, v] of Object.entries(r.rows)) md += `| ${k} | ${pct(v.correct)} | ${pct(v.wrong)} | ${pct(v.ask)} | ${pct(v.none)} |\n`;
  md += '\n';
}
writeFileSync('docs/benchmark.md', md);
console.log(md);
